NOISE_WORDS = nlp.CONTENT_TYPE_WORDS | nlp.AUDIENCE_WORDS


def _keywords(ctx: dict) -> list[str]:
    """Keyword list for an article: the topic first, then real phrases from the
    brief, minus content-type and audience noise that would read as a subject."""
    out = [ctx["topic"]]
    for kw in ctx["keywords"] or []:
        if kw.lower() not in [o.lower() for o in out]:
            out.append(kw)
    for item in nlp.ngrams(ctx["prompt"], (1, 3), 14):
        phrase = item["phrase"]
        toks = tokenize(phrase)
        if not toks or all(t in NOISE_WORDS for t in toks):
            continue
        if all(w in ctx["topic"].lower() for w in toks):
            continue  # already covered by the topic itself
        if phrase.lower() in [o.lower() for o in out]:
            continue
        out.append(phrase)
    return [nlp.fix_acronyms(k) for k in out[:8]]


def blog(ctx: dict) -> dict:
    target = _len_words(ctx["length"])
    kws = _keywords(ctx)
    n_sections = 3 if target <= 200 else 4 if target <= 300 else 5 if target <= 700 else 7
    sections = BLOG_SPINE[:n_sections]
    topic, brand, salt = ctx["topic"], ctx["brand"], ctx["salt"]
    tone = TONE_BANKS.get(ctx["tone"], TONE_BANKS["professional"])

    hook = pick([
        "{t} is not a creative problem. It is a systems problem with a word count.".format(t=title_case(topic)),
        "Nobody wakes up excited to write about {topic}. That is exactly why the process has to be boring.".format(topic=topic),
        "You can publish more, or you can publish faster. {t} only moves the needle when it is both.".format(t=title_case(topic)),
    ], salt, "hook")

    title = pick([
        "{t}: A Field Guide for {a}".format(t=title_case(topic), a=title_case(ctx["audience"])),
        "How to Do {t} Without Burning the Team Out".format(t=title_case(topic)),
        "{t} in {y}: {n} Steps That Actually Ship".format(t=title_case(topic), y=YEAR, n=band(salt, 5, 9)),
        "The {t} Playbook ({y} Edition)".format(t=title_case(topic), y=YEAR),
    ], salt, "title")
    meta_desc = "{t} for {a}: {n} steps, real numbers and copy-paste templates. {y} guide by {b}.".format(
        t=title_case(topic), a=ctx["audience"], n=n_sections, y=YEAR, b=brand)

    blocks: list[str] = ["# " + title, "", "_" + meta_desc + "_", "", hook, "",
                         "**Who this is for:** {a} who need more {t} output without extra headcount.".format(a=ctx["audience"], t=topic),
                         "**Read time:** {m} min | **Tone:** {tone} | **Language:** {lang}".format(
                             m=max(2, round(target / 225)), tone=ctx["tone"], lang=ctx["language"]),
                         ""]
    for i, (heading, key) in enumerate(sections):
        blocks.append("## " + title_case(heading.replace("{topic}", topic)))
        blocks.append("")
        if key == "how":
            steps = ["Write a 6-field brief: outcome, audience, angle, proof, keywords, CTA.",
                     "Generate three drafts against that brief, then merge the best paragraphs.",
                     "Cut 30 percent - adjectives, throat-clearing openers, anything without a number.",
                     "Publish, then score it every Friday on replies that mention buying."]
            labels = ["Brief", "Draft", "Cut", "Ship"]
            for step, (label, line) in enumerate(zip(labels, steps), start=1):
                blocks.append("{}. **{}** - {}".format(step, label, line))
            blocks.append("")
        blocks.append(_paragraph(dict(ctx, keywords=kws), key, i, 4 if key in ("why", "how", "tools") else 3))
        blocks.append("")
        if key == "tools":
            blocks.append("| Lever | Before | After |")
            blocks.append("| --- | --- | --- |")
            blocks.append("| Brief to draft | {} days | same day |".format(band(salt, 3, 6)))
            blocks.append("| Draft to publish | {} days | {} days |".format(band(salt, 4, 9), band(salt, 1, 2)))
            blocks.append("| Edits per piece | {} | {} |".format(band(salt, 6, 14), band(salt, 1, 3)))
            blocks.append("")
        if key == "problems":
            blocks.append("> If you fix only one thing, fix the brief. No shared definition of done turns {t} into taste.".format(t=topic))
            blocks.append("")

    blocks.append("## FAQ")
    blocks.append("")
    faq_answers = ["Usually {n} weeks, if the brief and review steps hold.".format(n=band(salt, 2, 8)),
                   "No. Start with one template and one channel; add tooling once the habit exists.",
                   "Yes - {t} rewards consistency more than talent.".format(t=topic),
                   "A good one shows the change: what you did, the number it moved, what you would cut."]
    for qi, q in enumerate(FAQ_TEMPLATES[:3]):
        blocks.append("**" + q.format(topic=topic, year=YEAR) + "**")
        blocks.append("")
        blocks.append(faq_answers[qi % len(faq_answers)])
        blocks.append("")
    blocks += ["## The bottom line",
               "Make {t} repeatable before you make it clever. One brief, one owner, one number to beat. {c}".format(t=topic, c=tone["close"]),
               "",
               "_Generated by {b} | keywords: {k}_".format(b=brand, k=", ".join(kws[:5]))]
    content = _clean_fluff("\n".join(blocks))
    stats = readability(content)
    return {
        "title": title,
        "content": content,
        "meta": {
            "meta_description": meta_desc.strip()[:158],
            "outline": [title_case(h) for h, _ in sections],
            "keywords": kws[:6],
            "word_count": stats["words"],
            "target_words": target,
            "reading_time_min": stats["reading_time_min"],
            "sections": n_sections,
            "readability": stats["flesch"],
        },
    }


