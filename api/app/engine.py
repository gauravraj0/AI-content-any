def text(ctx: dict) -> dict:
    fmt = str(ctx.get("format") or "email").lower()
    topic, brand, salt = ctx["topic"], ctx["brand"], ctx["salt"]
    tone = TONE_BANKS.get(ctx["tone"], TONE_BANKS["professional"])
    title = "Draft - " + topic

    if fmt.startswith("product"):
        title = "{t} - product description".format(t=title_case(topic))
        body = (
            "**{t}.** Built for {a} who refuse to spend another week on manual content ops.\n\n"
            "Three things matter here: speed, review, proof. {t} handles all three - {x}x throughput, "
            "one approval lane, and a scorecard attached to every piece.\n\n"
            "- {b1}\n- {b2}\n- From ${p}/mo, cancel any month\n\n_{c}_").format(
            t=title_case(topic), a=ctx["audience"], x=band(salt, 3, 9),
            b1=pick(["Ships in minutes, not sprints", "Zero setup, real output", "Your tone, not the model's"], salt, 1),
            b2=pick(["One review lane, full version history", "Reuses your brief, not a generic prompt"], salt, 2),
            p=band(salt, 19, 79), c=tone["close"])
    elif fmt.startswith("ad"):
        title = "Ad copy - " + pick(["paid social", "search", "display"], salt)
        body = (
            "**{h}**\n\n{t} gives {a} a draft in {s} seconds: brief, generate, approve, ship. "
            "No prompt engineering degree required.\n\n- {p1}\n- {p2}\n\n-> {cta}. Cancel whenever.").format(
            h=pick(["Stop writing from scratch.", "Your content queue is a lie.", "Publish daily without a bigger team."], salt, 1),
            t=title_case(topic), a=ctx["audience"], s=band(salt, 8, 45),
            p1=pick(["Templates for blog, social, ads and email", "One workspace, one source of truth"], salt, 2),
            p2=pick(["Usage analytics tied to pipeline", "Export to Markdown, HTML or your CMS"], salt, 3),
            cta=pick(["Start free", "Try it for 14 days", "See it on your own brief"], salt, 4))
    elif fmt.startswith("script") or fmt.startswith("video"):
        title = "Short-form script - " + topic
        beats = [
            "**HOOK (0-3s)** - \"{h}\"".format(h=pick([
                "{t} takes 6 hours. Or 6 minutes. Here is the difference.".format(t=title_case(topic)),
                "Nobody in your Slack is going to save this post - and that is the problem."], salt)),
            "",
            "**PROBLEM (3-15s)** - {a} lose {n} hours a week to blank-page start-up cost.".format(a=ctx["audience"], n=band(salt, 3, 11)),
            "",
            "**MEAT (15-45s)** - {tool}. Three beats: brief, draft, review. Say the number out loud: {p}% more shipped.".format(
                tool=pick(TOOLS, salt), p=band(salt, 12, 40)),
            "",
            "**CTA (45-55s)** - \"{c}\"".format(c=tone["close"]),
            "",
            "_Runtime ~{r}s | 4 beats | captions on_".format(r=band(salt, 48, 62)),
        ]
        body = "\n".join(beats)
    elif fmt.startswith("announce") or fmt.startswith("launch"):
        title = "Launch note - " + topic
        body = (
            "### {t} is live\n\nWe shipped it. {l}: {a} can now go from brief to published in one place, "
            "with a review trail and a scorecard.\n\n**What you get**\n"
            "1. Drafts in your tone, on brief\n2. One workspace for text, image and social\n"
            "3. Usage analytics tied to outcomes\n\n_{c}_\n\n- {b}").format(
            t=title_case(topic), l=pick(["What this means for you", "Here is what changed", "The short version"], salt),
            a=ctx["audience"], c=tone["close"], b=brand)
    else:  # email
        greeting = str(ctx.get("contact") or "there").strip().split()[0] or "there"
        lead_open = pick(tone["open"], salt)
        if lead_open.endswith(("-",)):
            lead_open = lead_open.rstrip("-,") + "."
        subject = pick([
            "{t}: {n} ideas for {f} this week".format(t=title_case(topic), n=band(salt, 3, 7), f=ctx["audience"].split()[0]),
            "Quick one on {t}".format(t=topic),
            "{t} - before you plan next month".format(t=title_case(topic)),
        ], salt, "subject")
        title = subject
        body = (
            "Hi {name},\n\n{o} Most teams treat {t} as a writing task. It is really a routing task: brief in, "
            "three drafts out, one approved, one number attached.\n\n"
            "Here is the version we would run this week:\n"
            "1. Pick {p}.\n2. Re-brief it in 6 fields (outcome, audience, angle, proof, keywords, CTA).\n"
            "3. Generate {n} drafts and merge the top two.\n4. Cut 30 percent. Publish. Score it Friday.\n\n"
            "{c}\n\n- {b}").format(
            name=greeting, o=lead_open, t=topic,
            p=pick(["the best-performing post", "the deadest campaign", "the one everyone complains about"], salt, 2),
            n=band(salt, 3, 5), c=tone["close"], b=brand)

    body = _clean_fluff(body)
    stats = readability(body)
    out_meta = {"format": fmt, "tone": ctx["tone"], "word_count": stats["words"],
                "reading_time_min": stats["reading_time_min"], "readability": stats["flesch"]}
    if fmt.startswith("email") or fmt == "text":
        out_meta["subject_line"] = title
        out_meta["preview_text"] = re.sub(r"\s+", " ", body)[:104]
    return {"title": title, "content": body, "meta": out_meta}


