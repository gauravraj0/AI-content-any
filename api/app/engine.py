def _paragraph(ctx: dict, section: str, idx: int, n_sentences: int) -> str:
    """claim -> mechanism -> proof -> consequence, phrased per section."""
    topic, audience = ctx["topic"], ctx["audience"]
    kws = ctx["keywords"] or [topic]
    kw = kws[idx % len(kws)]
    bank = {
        "why": [
            "Most {aud} do not lose to competitors on {topic} - they lose to their own handoffs.".format(aud=audience, topic=topic),
            "The cost of sloppy {kw} shows up two quarters later as pipeline nobody can explain.".format(kw=kw),
            "Teams that run {topic} as a written process ship {a}.{b}x more output with the same headcount.".format(topic=topic, a=band(ctx["salt"], 2, 5), b=band(section, 1, 9)),
            "There is a boring reason {kw} stalls: nobody wrote down who decides.".format(kw=kw),
        ],
        "what": [
            "At its simplest, {topic} is the loop between a brief, a draft, a review and a publish date.".format(topic=topic),
            "Strip the jargon and {kw} means one thing: a repeatable way to turn intent into finished copy.".format(kw=kw),
            "A {topic} system has three moving parts - inputs, an editor with taste, and one home for everything.".format(topic=topic),
            "Where {kw} usually fails is scope: every step assumes someone else owns the last one.".format(kw=kw),
        ],
        "how": [
            "Start from the outcome, written at the top of the brief, then delete every line that does not serve it.",
            "Generate {n} drafts against that same brief and merge the strongest paragraphs instead of picking a favourite.".format(n=band(ctx["salt"], 2, 4)),
            "Read it aloud. If a sentence needs a second breath, split it in two.",
            "Publish to {where}, then repurpose once - not before.".format(where=pick(["one channel", "two channels", "the newsletter first"], section)),
        ],
        "problems": [
            "The classic failure with {topic} is the blank-page tax: {m} minutes lost before the first sentence.".format(topic=topic, m=band(section, 20, 65)),
            "Review is where {kw} dies - one reviewer rewrites tone, the next rewrites structure, and nothing ships.".format(kw=kw),
            "Version drift is quiet and expensive: three drafts of the same post, two live links, zero owners.",
            "Volume without a template set turns {kw} into re-litigation.".format(kw=kw),
        ],
        "tools": [
            "We run {topic} on {tool}, because the tool matters far less than the constraint.".format(topic=topic, tool=pick(TOOLS, ctx["salt"])),
            "A {n}-field brief beats any prompt library: context is the multiplier for {kw}.".format(n=band(ctx["salt"], 4, 9), kw=kw),
            "Measure {m} weekly and ignore the vanity metrics.".format(m=pick(["time-to-first-draft", "publish cadence", "edits per piece", "organic lift"], section)),
            "Automate the handoff, never the judgement - that is the whole {topic} trick.".format(topic=topic),
        ],
        "mistakes": [
            "Do not publish {topic} content that explains the industry to people who already live in it.".format(topic=topic),
            "Skipping the {kw} outline costs more than it saves: about {p}% of the draft ends up unused.".format(kw=kw, p=band(section, 10, 40)),
            "Never edit the same draft twice without a fresh pair of eyes.",
            "Deleting the numbers is how a strong post turns into a vague one.",
        ],
        "action": [
            "This week: rebuild {pick} against this {topic} checklist.".format(pick=pick(["the best-performing post", "the deadest campaign", "next month's first send"], section), topic=topic),
            "Give {kw} one owner and a 15-minute daily review window. That is the entire change.".format(kw=kw),
            "Ship the smallest version, keep the scorecard, expand only what survives.",
            "Write tomorrow's brief today - {a} minutes now buy back {b} hours next week.".format(a=band(ctx["salt"], 2, 6), b=band(section, 3, 9)),
        ],
    }.get(section, [])
    if not bank:
        return ""
    lines: list[str] = []
    i = int(dice(ctx["salt"], section) * len(bank))
    while len(lines) < n_sentences and i < len(bank) * 3:
        cand = bank[i % len(bank)]
        if cand and cand not in lines:
            lines.append(cand)
        i += 1
    tone = TONE_BANKS.get(ctx["tone"], TONE_BANKS["professional"])
    body = " ".join(lines)
    if idx == 0 and tone.get("open"):
        body = pick(tone["open"], ctx["salt"], section) + " " + body
    return body


