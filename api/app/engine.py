def caption(ctx: dict) -> dict:
    topic, salt = ctx["topic"], ctx["salt"]
    wanted = [p for p in (ctx.get("platforms") or ["instagram", "linkedin", "x"]) if p in PLATFORMS] or ["instagram"]
    hooks = [
        "{t} in {y} looks less like writing and more like editing.".format(t=title_case(topic), y=YEAR),
        "We cut {p}% of our {t} drafts last quarter. Output went up.".format(p=band(salt, 40, 80), t=topic),
        "Nobody shares a polished paragraph. They share a specific number.",
        "Hot take: {t} is 10 percent ideas and 90 percent shipping cadence.".format(t=topic),
        "If your {t} process needs a meeting to start, it is not a process.".format(t=topic),
    ]
    ctas = ["Save this for Monday.", "Comment \u201cBRIEF\u201d and I will send the template.",
            "Repost if it saved you an hour.", "Full breakdown on the blog.",
            "Tell me the one step you would delete."]
    opts = []
    for i, plat in enumerate(wanted):
        rule = PLATFORMS[plat]
        hook = pick(hooks, salt, plat, "h")
        compact = rule["max"] <= 500
        if compact:  # X / Threads / TikTok need a short post, not a trimmed long one
            body = "{h}".format(h=hook)
        else:
            body = (
                "{h}\n\nThe move for {a}: brief, {n} drafts, merge, cut 30 percent, ship. "
                "One number per post, or the post is a mood and not a metric.").format(
                h=hook, a=ctx["audience"], n=band(salt, 2, 4))
        if rule["emoji"]:
            body += " " + " ".join(pick(EMOJIS, plat, j) for j in range(rule["emoji"]))
        raw_tags = [topic, "contentops", "aiwriting", "marketing", "growth", "copywriting", ctx["tone"]]
        tags = ["#" + re.sub(r"[^a-z0-9]", "", str(t).lower().replace(" ", "")) for t in raw_tags]
        tags = list(dict.fromkeys([t for t in tags if len(t) > 2]))
        tags = tags[: band(plat + str(i), rule["tags"][0], rule["tags"][1])]
        cta = pick(ctas, salt, plat, "cta") if not compact else pick(["Save this one.", "More on the blog.", "Go try it."], salt, plat, "scta")
        body = "{b}\n\n{c} {t}".format(b=body, c=cta, t=" ".join(tags))
        if len(body) > rule["max"]:            # hard ceiling, cut on a word boundary
            head = body[: rule["max"] - 4]
            body = head[: head.rfind(" ")].rstrip(",;:") + " …"
        body = _clean_fluff(body)
        opts.append({
            "platform": plat, "text": body, "hook": hook,
            "hashtags": [t.lstrip("#") for t in tags], "chars": len(body), "limit": rule["max"],
            "within_limit": len(body) <= rule["max"], "emoji": len(nlp.EMOJI_RE.findall(body)),
            "score": min(98, 62 + band(plat + str(i), 0, 30)),
            "best_time": pick(["Tue 08:30", "Wed 12:15", "Thu 17:40", "Mon 07:50", "Fri 09:20"], plat),
        })
    joined = "\n\n---\n\n".join(
        "### {p} | {c}/{l} chars\n\n{t}".format(p=o["platform"].upper(), c=o["chars"], l=o["limit"], t=o["text"])
        for o in opts)
    return {"title": "Social set - " + topic, "content": joined,
            "meta": {"options": opts, "platforms": wanted, "tone": ctx["tone"], "topic": topic,
                     "word_count": len(tokenize(joined))}}


# ------------------------------------------------------------------- rewrite
def rewrite(ctx: dict) -> dict:
    src = (ctx["source"] or "").strip()
    if len(tokenize(src)) < 6:
        return {"title": "Rewrite", "content": "", "meta": {"error": "Paste at least a sentence or two to rewrite."}}
    mode = ctx.get("mode") or "tone"
    tone_name = ctx["tone"] if ctx["tone"] in TONE_BANKS else "professional"
    tone = TONE_BANKS[tone_name]
    sents = nlp.sentences(src)
    changes: list[str] = []
    out: list[str] = []

    for s in sents:
        if mode == "concise":
            for phrase, good in (("in order to", "to"), ("due to the fact that", "because"),
                                 ("at this point in time", "now"), ("for the purpose of", "for")):
                new = re.sub(re.escape(phrase), good, s, flags=re.I)
                if new != s:
                    changes.append("\u201c%s\u201d \u2192 \u201c%s\u201d" % (phrase, good))
                    s = new
            s = re.sub(r"\b(very|really|quite|just|actually|basically|essentially|literally)\s+", "", s, flags=re.I)
            s = re.sub(r"\bit is (?:important|worth noting) to note that,?\s*", "", s, flags=re.I)
            if len(tokenize(s)) > 26:
                head, _, tail = s.partition(", and ")
                if not tail:
                    head, _, tail = s.partition(" but ")
                if tail and len(tokenize(head)) > 8:
                    out.append(head.rstrip(",; ") + ".")
                    s = tail[:1].upper() + tail[1:]
        s = FILLER_RE.sub("", s)
        s = re.sub(r"^[,;:\s]+", "", s)
        if mode in ("simplify", "tone"):
            swaps = list(WORD_SWAPS.items()) + list(tone["verb"].items()) if mode == "simplify" else tone["verb"].items()
            for bad, good in swaps:
                pat = re.compile(r"\b" + re.escape(bad) + r"\b", re.I)
                if pat.search(s):
                    s = pat.sub(good, s)
                    changes.append("\u201c%s\u201d \u2192 \u201c%s\u201d" % (bad, good))
        if tone_name == "professional":
            contractions = {"can't": "cannot", "won't": "will not", "don't": "do not", "it's": "it is",
                            "that's": "that is", "you're": "you are", "i'm": "I am", "we'll": "we will",
                            "we're": "we are", "they're": "they are", "isn't": "is not"}
            s = re.sub(r"\b(" + "|".join(contractions) + r")\b", lambda m: contractions[m.group(0).lower()], s, flags=re.I)
            s = re.sub(r"[!?]$", ".", s)
        elif tone_name == "casual":
            for formal, easy in (("it is ", "it's "), ("do not ", "don't "), ("we will ", "we'll "),
                                 ("you are ", "you're ")):
                s = s.replace(formal, easy)
        elif tone_name == "bold":
            s = re.sub(r"\b(maybe|perhaps|might|could|somewhat|kind of|a bit)\b", "will", s, flags=re.I)
            s = re.sub(r"\bi think\b|\bwe believe\b", "", s, flags=re.I)
        s = re.sub(r"\s{2,}", " ", s).strip()
        s = re.sub(r"^([a-z])", lambda m: m.group(1).upper(), s)
        if s and s not in out:
            out.append(s.rstrip(".") + ".")

    if mode == "expand":
        extra = ["Put a number on it: {p}% of teams that track this hit the target early.".format(p=band(ctx["salt"], 12, 48)),
                 "Owner and deadline, in writing - that one habit is where {t} stops slipping.".format(t=ctx["topic"]),
                 "Name the reader's objection before they do; agreement gets faster."]
        out = out[:2] + [extra[0]] + out[2:4] + [extra[1]] + out[4:] + [extra[2]]
    if mode != "concise":
        out.insert(0, pick(tone["open"], ctx["salt"], "open"))
        out.append(tone["close"])

    body = _clean_fluff(" ".join(dict.fromkeys([o for o in out if o])))
    before, after = readability(src), readability(body)
    changes.insert(0, "tone \u2192 " + tone_name)
    diff_words = after["words"] - before["words"]
    changes.insert(1, "{a} \u2192 {b} words ({s}{d})".format(a=before["words"], b=after["words"],
                                                             s="-" if diff_words < 0 else "+", d=abs(diff_words)))
    changes.insert(2, "readability {x} \u2192 {y}".format(x=before["flesch"], y=after["flesch"]))
    kept = round(sum(1 for t in tokenize(body) if t in set(tokenize(src))) / max(1, len(tokenize(body))), 2)
    return {"title": "Rewrite - " + ctx["topic"][:40], "content": body,
            "meta": {"before": before, "after": after, "readability_delta": round(after["flesch"] - before["flesch"], 1),
                     "changes": changes[:10], "mode": mode, "tone": tone_name, "retention": kept,
                     "word_count": after["words"]}}


# -------------------------------------------------------------------- summarize
def _heading_set(raw: str) -> set:
    """Titles, H2s and italic standfirsts are furniture, not content to summarise."""
    def norm(s: str) -> str:
        return re.sub(r"[^a-z0-9 ]", "", (s or "").lower().strip()).strip()
    heads = re.findall(r"^#{1,6}\s*(.+)$", raw or "", re.M)
    italics = re.findall(r"^\s*_([^_\n]{3,200})_\s*$", raw or "", re.M)
    return {norm(h) for h in heads + italics if norm(h)}


def summarize(ctx: dict) -> dict:
    raw_src = (ctx["source"] or "").strip()
    furniture = _heading_set(raw_src)
    src = nlp.strip_md(raw_src).strip()
    if len(tokenize(src)) < 14:
        return {"title": "Summary", "content": "", "meta": {"error": "Paste at least a few sentences to summarise."}}
    def _keep(s: str) -> bool:
        clean = re.sub(r"[^a-z0-9 ]", "", s.lower()).strip()
        if len(tokenize(s)) < 6 or JUNK_LINE.search(s):
            return False
        if clean in furniture:
            return False
        return not any(clean.startswith(h[:40]) for h in furniture if len(h) > 12)

    sents = [s for s in nlp.sentences(src) if _keep(s)]
    if not sents:
        sents = nlp.sentences(src)
    terms = dict(key_terms(src, 4))
    top = list(terms.keys())
    scored = []
    for i, s in enumerate(sents):
        toks = tokenize(s)
        if len(toks) < 5:
            continue
        hits = sum(1 for t in toks if t in top[:18])
        pos_bonus = 1.35 if i < 2 else (1.15 if i >= len(sents) - 2 else 1.0)
        num_bonus = 1.5 if re.search(r"\d", s) else 1.0
        length_pen = 0.6 if len(toks) > 45 else 1.0
        scored.append((hits * pos_bonus * num_bonus * length_pen / math.log(2 + len(toks)), s))
    if not scored:
        scored = [(1.0, sents[0])]
    scored.sort(key=lambda x: -x[0])
    n = {"short": 3, "medium": 5, "long": 8}.get(ctx["length"], 4)
    chosen = {s for _, s in scored[:n]}
    ordered = [s for s in sents if s in chosen] or [scored[0][1]]
    lead = ordered[0]
    numbers = re.findall(r"\$?\d[\d.,]*%?", src)[:3]
    tldr = lead.rstrip(".")[:190] + "." + (" Key numbers: " + ", ".join(numbers) + "." if numbers else "")
    bullets = "\n".join("- " + s for s in ordered)
    actions = [s for s in ordered if re.search(r"\b(must|should|need to|next|plan|ship|review|deadline|assign|by \w+day)\b", s, re.I)]
    stats = readability(src)
    compressed = round(len(tokenize(bullets)) / max(1, stats["words"]), 2)
    out = "**TL;DR** - {t}\n\n**Key points**\n{b}".format(t=tldr, b=bullets)
    if actions:
        out += "\n\n**Action items**\n" + "\n".join("- [ ] " + a for a in actions[:4])
    out += "\n\n_Compressed {w} words to {c} ({p}% shorter).".format(
        w=stats["words"], c=len(tokenize(bullets)), p=max(0, round((1 - compressed) * 100)))
    return {"title": "Summary - " + ctx["topic"][:40], "content": out,
            "meta": {"tldr": tldr, "points": ordered, "actions": actions[:4], "compression": compressed,
                     "keywords": top[:6], "source_stats": stats, "word_count": len(tokenize(out))}}


# ------------------------------------------------------------------------ seo
def seo(ctx: dict) -> dict:
    topic, salt = ctx["topic"], ctx["salt"]
    seed_terms = [t["phrase"] for t in nlp.ngrams(ctx["prompt"] or topic, (1, 3), 8)]
    seeds = list(dict.fromkeys([topic] + seed_terms[:4]))
    modifiers = ["for beginners", "examples", "template", "checklist", "vs", "software", "strategy",
                 "best practices", "guide", "pricing", "alternatives", "for small business", "statistics"]
    intents = ["informational", "commercial", "transactional", "navigational"]
    rows: list[dict] = []
    seen: set[str] = set()
    for base in seeds:
        for m in modifiers:
            kw = ("%s %s" % (base, m)).strip().lower()
            if len(kw) > 62 or kw in seen:
                continue
            seen.add(kw)
            vol = log_scale(kw + salt, 40, 41000)
            diff = band(kw, 6, 78)
            rows.append({"keyword": kw, "volume": vol, "difficulty": diff,
                         "cpc": round(band(kw, 40, 1450) / 100, 2),
                         "intent": pick(intents, kw),
                         "click_pct": band(kw, 22, 74),
                         "priority": round(min(99, (vol ** 0.28) * (100 - diff) / 6 + band(kw, 0, 12)))})
    rows.sort(key=lambda r: -r["priority"])
    rows = rows[:24]
    questions = ["What is %s?" % topic, "How does %s work?" % topic,
                 "Is %s worth it in %s?" % (topic, YEAR), "What tools do I need for %s?" % topic,
                 "How long until %s shows results?" % topic]
    primary = rows[0]["keyword"] if rows else topic
    meta_title = pick([
        "{t}: {n} Proven Steps ({y})".format(t=title_case(primary), n=band(salt, 5, 9), y=YEAR),
        "{t} - Templates, Checklist and Examples".format(t=title_case(topic)),
        "Best {t} Setup in {y} (Free Template)".format(t=title_case(topic), y=YEAR),
    ], salt, "mt")
    meta_desc = "{t}, minus the fluff: a {n}-step {k} workflow, free template and the numbers {a} actually need. {y}.".format(
        t=title_case(topic), n=band(salt, 4, 7), k=primary, a=ctx["audience"], y=YEAR)
    outline = [
        "# " + meta_title,
        "## Why {t} matters in {y}".format(t=topic, y=YEAR) + "  (informational intent)",
        "## " + title_case(primary) + " - definition and scope  (FAQ target)",
        "## Step-by-step workflow + free template  (transactional - CTA above the fold)",
        "## Comparison table: options by price and speed  (featured snippet bait)",
        "## Mistakes that cost teams {n} weeks".format(n=band(salt, 2, 9)),
        "## FAQ  (answer each in 42 words for snippet eligibility)",
        "## CTA: {b} demo  (commercial intent)".format(b=ctx["brand"]),
    ]
    faq_answers = ["Most teams see a measurable difference in 2-4 weeks, provided one person owns the brief.",
                   "It depends on volume: start with one channel and one template, then widen.",
                   "Yes - if you can write the outcome and the number you want to move.",
                   "One template, one review lane, one scorecard. Everything else is optional.",
                   "About a week for the first publishable version, if the brief is done."]
    table = ("\n\n## Keyword targets\n\n| Keyword | Intent | Vol/mo | Difficulty | CPC | Priority |\n"
             "| --- | --- | --- | --- | --- | --- |\n")
    table += "\n".join(
        "| {kw} | {it} | {vol:,} | {dif} | ${cpc} | {pri} |".format(
            kw=r["keyword"], it=r["intent"], vol=r["volume"], dif=r["difficulty"], cpc=r["cpc"], pri=r["priority"])
        for r in rows[:12])
    faq = "\n\n".join("**%s**\n\n%s" % (q, a) for q, a in zip(questions, faq_answers))
    body = "\n".join(outline) + table + "\n\n## FAQ block\n\n" + faq
    score = min(96, 42 + len(rows) // 2 + (12 if len(meta_title) <= 60 else 0) + (10 if len(meta_desc) <= 158 else 0))
    return {"title": "SEO brief - " + topic, "content": _clean_fluff(body),
            "meta": {"keywords": rows, "primary": primary, "total_volume": sum(r["volume"] for r in rows),
                     "meta_title": meta_title, "meta_title_len": len(meta_title),
                     "meta_description": meta_desc.strip(), "meta_desc_len": len(meta_desc.strip()),
                     "outline": outline, "questions": questions, "score": score,
                     "word_target": band(topic, 1100, 2400),
                     "internal_links": ["/templates/" + topic.split()[0].lower(), "/features/blog-writer", "/pricing"],
                     "word_count": len(tokenize(body))}}


# --------------------------------------------------------------------- analyze
def analyze(ctx: dict) -> dict:
    raw = (ctx["source"] or "").strip()
    src = nlp.strip_md(raw)
    toks = tokenize(src)
    if len(toks) < 20:
        return {"title": "Analysis", "content": "", "meta": {"error": "Paste at least 20 words to run the analyzer."}}
    stats = readability(src)
    sents = nlp.sentences(src)
    low = src.lower()
    salt = ctx["salt"]

    flagged = {}
    for label, bank in AI_FLAGS.items():
        found = sorted({w for w in bank if re.search(r"\b" + re.escape(w) + r"\b", low)})
        if found:
            flagged[label] = found
    flag_hits = sum(len(v) for v in flagged.values())
    per_100 = flag_hits / max(1, len(toks)) * 100

    lens = [len(tokenize(s)) for s in sents] or [0]
    mean = sum(lens) / len(lens)
    var = sum((x - mean) ** 2 for x in lens) / max(1, len(lens))
    burstiness = math.sqrt(var) / max(1.0, mean)
    diversity = len(set(toks)) / max(1, len(toks))
    openers = [s.split()[0].lower().strip(",.;:!?") for s in sents if s.split()]
    rep_openers = 1 - len(set(openers)) / max(1, len(openers))
    para_lens = [len(tokenize(x)) for x in re.split(r"\n\s*\n", raw) if x.strip()] or [0]
    if len(para_lens) > 1:
        pm = sum(para_lens) / len(para_lens)
        pvar = sum((x - pm) ** 2 for x in para_lens) / len(para_lens)
        uniform_paras = max(0.0, 1 - math.sqrt(pvar) / max(1.0, pm))
    else:
        uniform_paras = 0.0
    numbers = len(re.findall(r"\d", src)) / max(1, len(sents))
    adverb_heavy = len(re.findall(r"\b(ly)\b", low)) / max(1, len(toks))
    hedges = len(re.findall(r"\b(maybe|perhaps|might|could|somewhat|very|really|just)\b", low)) / max(1, len(sents))

    ai_score = 100.0
    ai_score -= max(0.0, min(60.0, 260.0 * (burstiness - 0.06)))
    ai_score -= max(0.0, min(16.0, 90.0 * (diversity - 0.42)))
    ai_score += max(0.0, min(34.0, 46.0 * (per_100 - 0.9)))
    ai_score += max(0.0, min(16.0, 60.0 * (uniform_paras - 0.62)))
    ai_score += max(0.0, min(10.0, 30.0 * (rep_openers - 0.5)))
    ai_score = round(max(2.0, min(99.0, ai_score)), 1)
    human_score = round(100 - ai_score, 1)

    pos = sum(1 for t in toks if t in POSITIVE)
    neg = sum(1 for t in toks if t in NEGATIVE)
    sentiment = "positive" if pos > neg * 1.4 else ("negative" if neg > pos * 1.4 else "neutral")
    tone_scores = {}
    for name, bank in TONE_BANKS.items():
        sc = sum(1 for w in bank["verb"] if re.search(r"\b" + re.escape(w) + r"\b", low))
        sc += sum(2 for o in bank["open"] if o.lower().strip(":,-") in low)
        tone_scores[name] = sc
    detected_tone = max(tone_scores.items(), key=lambda kv: kv[1])[0] if max(tone_scores.values()) > 0 else "neutral"

    density = [{"term": t, "count": c, "pct": round(c / max(1, len(toks)) * 100, 2)} for t, c in key_terms(src, 4)[:8]]
    structure = {"headings": len(re.findall(r"^#{1,6} ", raw, re.M)),
                 "lists": len(re.findall(r"^\s*(?:[-*]|\d+\.)\s", src, re.M)),
                 "table_rows": len(re.findall(r"^\|", raw, re.M)),
                 "links": len(re.findall(r"\[[^\]]+\]\([^)]+\)", raw)),
                 "images": len(re.findall(r"!\[[^\]]*\]\(", raw)),
                 "avg_sentence_words": round(mean, 1), "longest_sentence": max(lens)}

    fixes = []
    if per_100 > 1.1:
        flat = [w for v in flagged.values() for w in v]
        fixes.append({"issue": "AI-tell vocabulary", "impact": "high",
                      "detail": "%d flagged words (%s). Swap them for concrete verbs and objects." % (
                          len(flat), ", ".join(flat[:6]) or "none")})
    if burstiness < 0.28:
        fixes.append({"issue": "Metronome sentence lengths", "impact": "high",
                      "detail": "Sentence length variation is %.2f (sigma/mean). Follow a 30-word sentence with a 6-word one." % burstiness})
    if stats["flesch"] < 45:
        fixes.append({"issue": "Dense prose", "impact": "medium",
                      "detail": "Flesch %.1f is about grade %.1f. Aim for 60+ for %s." % (stats["flesch"], stats["grade"], ctx["audience"])})
    if uniform_paras > 0.75:
        fixes.append({"issue": "Uniform paragraph blocks", "impact": "medium",
                      "detail": "Every block is the same size. Turn one into a single-line punch or a list."})
    if numbers < 0.35:
        fixes.append({"issue": "No proof", "impact": "high",
                      "detail": "%.2f numerals per sentence. Add one number per section or drop the claim." % numbers})
    if rep_openers > 0.45:
        fixes.append({"issue": "Repeated sentence openers", "impact": "medium",
                      "detail": "%d%% of sentences start with the same word." % round(rep_openers * 100)})
    if hedges > 0.5:
        fixes.append({"issue": "Hedging language", "impact": "low",
                      "detail": "Cut maybe / might / could. Definite claims age better."})
    if structure["headings"] < max(1, len(sents) // 12):
        fixes.append({"issue": "Thin structure", "impact": "low",
                      "detail": "Add an H2 every 3-4 paragraphs so readers can scan and skip."})
    if not fixes:
        fixes.append({"issue": "Nothing structural to fix", "impact": "none",
                      "detail": "Rhythm, proof and readability are healthy. Ship it."})

    projected = {}
    if fixes:
        projected = {"readability": round(min(92, stats["flesch"] + 9 + len(fixes) * 1.4), 1),
                     "human_score": round(min(99, human_score + sum(4 for f in fixes if f["impact"] == "high")
                                              + sum(2 for f in fixes if f["impact"] == "medium")), 1)}

    content_score = round(max(3, min(99,
        0.34 * stats["flesch"]
        + 0.24 * human_score
        + 0.16 * min(100, numbers * 60 + 40)
        + 0.14 * min(100, 40 + structure["headings"] * 14 + structure["lists"] * 10)
        + 0.12 * min(100, diversity * 130))), 0)
    verdict = ("Publish as-is" if content_score >= 82 and ai_score < 30 else
               "Light edit" if content_score >= 68 else
               "Rewrite pass recommended" if content_score >= 52 else "Rebuild from outline")
    bars = [
        {"label": "Readability", "value": int(min(100, stats["flesch"]))},
        {"label": "Human rhythm", "value": int(min(100, burstiness * 190))},
        {"label": "Lexical variety", "value": int(min(100, diversity * 120))},
        {"label": "Proof density", "value": int(min(100, 40 + numbers * 55))},
        {"label": "Structure", "value": int(min(100, 40 + structure["headings"] * 12 + structure["lists"] * 6))},
        {"label": "Original phrasing", "value": int(max(8, 100 - per_100 * 26))},
    ]
    lines = ["# Content report - " + ctx["topic"][:36], "",
             "**Overall %d/100** | verdict: %s" % (content_score, verdict),
             "- AI-generated likelihood: **%s%%** (human fingerprint %s%%)" % (ai_score, human_score),
             "- Readability: Flesch %.1f | grade %.1f | %d words | %d min" % (
                 stats["flesch"], stats["grade"], stats["words"], stats["reading_time_min"]),
             "- Tone: %s | sentiment: %s" % (detected_tone, sentiment),
             "", "## Signal breakdown", ""]
    lines += ["- %s: %d/100" % (b["label"], b["value"]) for b in bars]
    lines += ["", "## Fixes worth the time", ""]
    lines += ["1. **%s** (%s) - %s" % (f["issue"], f["impact"], f["detail"]) for f in fixes]
    if projected:
        lines += ["", "## Projected after fixes", "",
                  "- Readability %.1f -> %s" % (stats["flesch"], projected["readability"]),
                  "- Human fingerprint %s%% -> %s%%" % (human_score, projected["human_score"])]
    lines += ["", "_Analysed %d sentences, %d words | engine build %s_" % (len(sents), len(toks), salt[:6])]
    return {"title": "Content report - " + ctx["topic"][:40], "content": "\n".join(lines),
            "meta": {"content_score": content_score, "ai_probability": ai_score, "human_score": human_score,
                     "readability": stats, "tone": detected_tone, "sentiment": sentiment,
                     "keyword_density": density, "flags": flagged, "per_100_words": round(per_100, 2),
                     "burstiness": round(burstiness, 3), "lexical_diversity": round(diversity, 3),
                     "structure": structure, "metrics": bars, "fixes": fixes, "verdict": verdict,
                     "projected": projected, "word_count": stats["words"]}}


