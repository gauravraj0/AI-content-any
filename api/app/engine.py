_SENT_START = re.compile(r"(^|(?<=[.!?])\s+|\n\s*)([a-z])", re.M)


def _recap(text: str) -> str:
    """Capitalise sentence/line starts, skipping URLs and inline labels."""
    def rep(m: re.Match) -> str:
        ch = m.group(2)
        tail = text[m.end():m.end() + 12]
        if re.match(r"^[a-z0-9.-]*://", tail) or re.match(r"^[a-z0-9.-]*\.[a-z]{2,}/", tail):
            return m.group(0)
        return m.group(1) + ch.upper()
    return _SENT_START.sub(rep, text)


def _clean_fluff(text: str) -> str:
    out = text or ""
    for bad, good in WORD_SWAPS.items():
        out = re.sub(r"\b" + re.escape(bad) + r"\b", good, out, flags=re.I)
    out = re.sub(r"\s+([,.;:!?])", r"\1", out)
    out = re.sub(r"[ \t]{2,}", " ", out)
    out = _recap(out)
    out = nlp.fix_articles(out)
    out = re.sub(r"[ \t]{2,}", " ", out)
    return out.strip()


def _len_words(length: str) -> int:
    return {"tiny": 90, "short": 180, "medium": 420, "long": 800, "epic": 1400}.get(length, 420)


