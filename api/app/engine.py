def run(kind: str, params: dict) -> dict:
    if kind not in DISPATCH:
        raise ValueError("unknown generation kind: %s" % kind)
    ctx = _norm(params)
    result = DISPATCH[kind](ctx)
    chars_in = len((params.get("source") or params.get("prompt") or ""))
    latency = band("%s|%s" % (kind, ctx["salt"]), 240, 1400) + int(chars_in * 0.35)
    return {
        "kind": kind,
        "title": result["title"],
        "content": result["content"],
        "meta": result["meta"],
        "engine": {"model": MODELS[kind], "credits": CREDITS[kind], "latency_ms": latency,
                   "words_out": len(tokenize(result["content"])), "chars_in": chars_in,
                   "temperature": params.get("temperature", 0.7), "seed": int(dice(ctx["salt"], kind) * 99999),
                   "mode": "local-engine"},
    }


def estimate(kind: str, params: dict) -> dict:
    """Pre-flight cost + time estimate shown in the composer."""
    chars = len((params.get("source") or params.get("prompt") or ""))
    target = _len_words(params.get("length") or "medium")
    secs = round((band(kind, 320, 1500) + chars * 0.35) / 1000, 1)
    words = target if kind in ("blog", "text") else max(40, int(chars * 0.35))
    if kind in ("summarize", "analyze") and chars:
        words = {"short": 60, "medium": 120, "long": 200}.get(params.get("length") or "medium", 120)
    return {"kind": kind, "credits": CREDITS.get(kind, 3), "seconds": secs,
            "expected_words": words, "model": MODELS.get(kind, "nebula-copy-2")}
